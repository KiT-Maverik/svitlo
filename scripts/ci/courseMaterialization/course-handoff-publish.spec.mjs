import test from 'node:test';
import assert from 'node:assert/strict';
import { gitBlob } from './course-gate.mjs';
import { getPR, manifestDigest, verifyCommittedInventory, reconcileCommittedPR } from './course-handoff-publish.mjs';

const id = '663572e7-bd85-4516-86e2-3de07d209e03';
const root = 'content/book/data/courses/3/' + id;
const source = root + '/content/episode/draft.ts';
const data = Buffer.from('reviewed handoff').toString('base64');
const draft = root + '/draft.ts';
const index = root + '/index.ts';
const sourceBlobSha = gitBlob(Buffer.from('reviewed Course draft'));
const manifest = {
  version: 2,
  operation: 'typed-course-stage5',
  sourcePath: draft,
  sourceBlobSha,
  materializedPath: index,
  repo: 'owner/repo',
  number: 5,
  branch: 'course/sky',
  courseId: id,
  head: 'a'.repeat(40),
  entries: [
    { path: source, data },
    { path: index, data },
  ],
  inventory: {
    lessons: [],
    assessments: [],
    episodes: [
      {
        type: 'episode',
        id,
        kind: 'new',
        status: 'pending-episode-scenario',
        placementPath: root + '/content/episode',
        sourcePath: source,
        placementSourcePath: source,
        orderPath: [0],
      },
    ],
  },
};
const proof = {
  repo: manifest.repo,
  number: 5,
  branch: manifest.branch,
  courseId: id,
  reviewedHead: manifest.head,
  commit: 'b'.repeat(40),
  digest: manifestDigest(manifest),
};
const commit = {
  sha: proof.commit,
  parents: [{ sha: manifest.head }],
  tree: { sha: 'c'.repeat(40) },
  message: 'Course-PR: #5\nCourse-Inventory-Manifest: ' + proof.digest,
};
const tree = {
  tree: [source, index].map(path => ({
    path,
    type: 'blob',
    mode: '100644',
    sha: gitBlob(Buffer.from(data, 'base64')),
  })),
};
const parent = { sha: proof.reviewedHead, tree: { sha: 'e'.repeat(40) } };
const parentTree = { tree: [{ path: draft, type: 'blob', mode: '100644', sha: sourceBlobSha }] };
const api = async route =>
  route === 'git/commits/' + proof.commit
    ? commit
    : route === 'git/commits/' + proof.reviewedHead
      ? parent
      : route === 'git/trees/' + parent.tree.sha + '?recursive=1'
        ? parentTree
        : tree;
test('Course PR metadata PATCH sends plain JSON without unsupported If-Match', async () => {
  const calls = [];
  const transport = async (url, options) => {
    calls.push({ url, options });
    return {
      ok: true,
      status: 200,
      headers: { get: name => (name === 'etag' ? 'revision' : null) },
      json: async () => ({ number: 5, body: 'Updated inventory' }),
    };
  };
  const result = await getPR('pulls/5', 'PATCH', { body: 'Updated inventory' }, transport);
  assert.equal(result.pr.body, 'Updated inventory');
  assert.equal(calls.length, 1);
  assert.equal(calls[0].options.method, 'PATCH');
  assert.equal(calls[0].options.headers['If-Match'], undefined);
  assert.equal(calls[0].options.headers['Content-Type'], 'application/json');
  assert.deepEqual(JSON.parse(calls[0].options.body), { body: 'Updated inventory' });
});

test('Course PR metadata reports the actual failed GitHub method and message', async () => {
  const transport = async () => ({
    ok: false,
    status: 400,
    json: async () => ({ message: 'Unsupported conditional request' }),
  });
  await assert.rejects(
    () => getPR('pulls/5', 'PATCH', { body: 'updated' }, transport),
    /Course PR metadata PATCH HTTP 400: Unsupported conditional request/,
  );
});

test('metadata only accepts exact manifest and committed generated bytes', async () => {
  assert.equal(await verifyCommittedInventory(manifest, proof, api), true);
  await assert.rejects(verifyCommittedInventory({ ...manifest, entries: [] }, proof, api), /proof/);
  await assert.rejects(
    verifyCommittedInventory(manifest, proof, async route =>
      route === 'git/trees/' + commit.tree.sha + '?recursive=1' ? { tree: [] } : api(route),
    ),
    /differs/,
  );
  await assert.rejects(
    verifyCommittedInventory(manifest, proof, async route =>
      route === 'git/commits/' + proof.commit ? { ...commit, parents: [] } : api(route),
    ),
    /transaction/,
  );
});
function fake({ race = false, head = proof.commit } = {}) {
  let body = 'Owner notes\n- [x] Stage 4',
    reads = 0,
    writes = 0;
  const pr = () => ({
    number: 5,
    state: 'open',
    draft: true,
    head: { repo: { full_name: proof.repo }, ref: proof.branch, sha: head },
    body,
    updated_at: 'stable',
  });
  return {
    get writes() {
      return writes;
    },
    get body() {
      return body;
    },
    async request(route, method, patch, tag) {
      if (method === 'PATCH') {
        assert.equal(tag, undefined, 'GitHub does not support If-Match on unsafe PATCH');
        writes++;
        body = patch.body;
      } else {
        reads++;
        if (race && reads === 2) body += '\nConcurrent edit';
      }
      return { pr: pr(), etag: 'version' };
    },
  };
}
test('reconcile is idempotent and preserves owner notes; stale or edited PR is untouched', async () => {
  const ok = fake();
  assert.equal(await reconcileCommittedPR(manifest, proof, ok.request), true);
  assert.equal(await reconcileCommittedPR(manifest, proof, ok.request), false);
  assert.equal(ok.writes, 1);
  assert.match(ok.body, /Owner notes/);
  for (const bad of [fake({ race: true }), fake({ head: 'd'.repeat(40) })]) {
    await assert.rejects(reconcileCommittedPR(manifest, proof, bad.request));
    assert.equal(bad.writes, 0);
  }
});

test('requires exact consumed draft deletion, parent source identity and generated index', async () => {
  await assert.rejects(
    verifyCommittedInventory(manifest, proof, async route =>
      route === 'git/trees/' + commit.tree.sha + '?recursive=1'
        ? { tree: [...tree.tree, ...parentTree.tree] }
        : api(route),
    ),
    /still exists/,
  );
  await assert.rejects(
    verifyCommittedInventory(manifest, proof, async route =>
      route === 'git/trees/' + parent.tree.sha + '?recursive=1' ? { tree: [] } : api(route),
    ),
    /Reviewed draft blob/,
  );
});
test('failed metadata-only write can retry without materializing source again', async () => {
  const ok = fake();
  let fail = true;
  const request = async (...args) => {
    if (args[1] === 'PATCH' && fail) {
      fail = false;
      throw Error('Temporary metadata API failure');
    }
    return ok.request(...args);
  };
  await verifyCommittedInventory(manifest, proof, api);
  await assert.rejects(reconcileCommittedPR(manifest, proof, request), /Temporary metadata/);
  assert.equal(ok.writes, 0);
  await verifyCommittedInventory(manifest, proof, api);
  assert.equal(await reconcileCommittedPR(manifest, proof, request), true);
  assert.equal(await reconcileCommittedPR(manifest, proof, request), false);
  assert.equal(ok.writes, 1);
});
