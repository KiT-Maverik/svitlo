/**
 * Approved editorial YAML -> typed Lesson Data. Build time only.
 * Ownership is restricted to the generated/ directory of one canonical Lesson.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import Ajv2020 from 'ajv2020/dist/2020.js';

export const repoRoot = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const schemaRoot = path.join(repoRoot, 'studio/skills/lesson-workflow');
const marker = '// Generated by scripts/lesson-builder.mjs; DO NOT EDIT.';
const uuidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const exactUuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const assetTypes = new Set(['image', 'audio', 'video', 'carousel']);
const questionTypes = ['selectOneAnswer', 'selectMultipleAnswers', 'matchBlocks', 'answerWithText', 'answerWithNumber', 'orderSequence', 'buildAnswerWithBlocks', 'fillBlanksWithBlocks', 'fillBlanksWithText'];
const schemas = [
  ['methodology', 'lesson-methodology-frontmatter.schema.json'],
  ['content', 'lesson-content.schema.json'],
  ['questions', 'lesson-questions.schema.json'],
];

export class BuilderDiagnostic extends Error {
  constructor(file, field, message) {
    super(file + ':' + field + ': ' + message);
    this.name = 'BuilderDiagnostic';
    this.file = file;
    this.field = field;
  }
}
function fail(file, field, message) {
  throw new BuilderDiagnostic(file, field, message);
}
function sha(value) {
  return crypto.createHash('sha256').update(value).digest('hex');
}
function uuid5(namespace, name) {
  const bytes = Buffer.from(namespace.replaceAll('-', ''), 'hex');
  const digest = crypto.createHash('sha1').update(bytes).update(name).digest();
  digest[6] = (digest[6] & 15) | 0x50;
  digest[8] = (digest[8] & 63) | 0x80;
  const h = digest.subarray(0, 16).toString('hex');
  return [h.slice(0, 8), h.slice(8, 12), h.slice(12, 16), h.slice(16, 20), h.slice(20)].join('-');
}
function noSymlinks(target) {
  let current = path.parse(path.resolve(target)).root;
  for (const part of path.resolve(target).slice(current.length).split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    if (fs.existsSync(current) && fs.lstatSync(current).isSymbolicLink())
      throw new Error('Refusing symlink: ' + current);
  }
}
function read(file) {
  noSymlinks(file);
  return fs.readFileSync(file, 'utf8');
}
function loadYAML(text, filename) {
  try {
    const value = yaml.load(text, { schema: yaml.JSON_SCHEMA });
    if (!value || typeof value !== 'object' || Array.isArray(value)) fail(filename, '$', 'expected YAML mapping');
    return value;
  } catch (error) {
    if (error instanceof BuilderDiagnostic) throw error;
    fail(filename, '$', error.message);
  }
}
function loadMethodology(text, filename) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(text);
  if (!match) fail(filename, '$', 'methodology.md must have YAML frontmatter');
  return loadYAML(match[1], filename);
}
function schemaValidators() {
  const ajv = new Ajv2020({ allErrors: true, strict: false, validateFormats: false });
  return Object.fromEntries(schemas.map(([key, name]) => {
    const schema = JSON.parse(read(path.join(schemaRoot, name)));
    return [key, ajv.compile(schema)];
  }));
}
function validateSchema(validator, input, filename) {
  if (validator(input)) return;
  const error = validator.errors?.[0];
  const field = '$' + (error?.instancePath ?? '').replaceAll('/', '.')
    + (error?.keyword === 'required' ? '.' + error.params.missingProperty : '');
  fail(filename, field, error?.message || 'invalid schema');
}
function unique(items, file, field) {
  const found = new Set();
  for (const [i, value] of items.entries()) {
    if (found.has(value)) fail(file, field + '[' + i + ']', 'duplicate key: ' + value);
    found.add(value);
  }
}
function sameList(a, b) {
  return JSON.stringify(a) === JSON.stringify(b);
}
function required(condition, file, field, message) {
  if (!condition) fail(file, field, message);
}
function safeAsset(root, asset, file, field) {
  if (!asset || typeof asset !== 'string' || asset.startsWith('/') || asset.includes('\\') ||
    asset.split('/').some(part => !part || part === '.' || part === '..') || /^https?:/i.test(asset))
    fail(file, field, 'asset must be a safe textbook-relative file path');
  const location = path.resolve(root, asset);
  required(location.startsWith(root + path.sep), file, field, 'asset path escapes the textbook');
  noSymlinks(location);
  return fs.existsSync(location) && fs.statSync(location).isFile();
}
function sourceText(value, language) {
  if (typeof value === 'object' && value?.invariant === true) return value.value;
  return { [language]: value };
}
function loc(value, language, file, field) {
  required(typeof value === 'string' && value.length > 0, file, field, 'source-language text is required');
  return { [language]: value };
}
function issue(requirements, kind, location, detail, owner = null) {
  requirements.push({ kind, location, detail, status: 'pending', ...(owner ? { owner } : {}) });
}
function blockData(block, lessonId, language, root, requirements, field, file = 'content.yaml') {
  const value = { id: uuid5(lessonId, 'block/' + field), slug: block.key, type: block.type };
  const spec = block.contentSpec ?? {};
  if (block.type === 'text') return { ...value, value: loc(block.sourceText, language, file, field + '.sourceText') };
  if (block.type === 'markdown') return { ...value, locales: loc(block.sourceText, language, file, field + '.sourceText') };
  if (block.type === 'scene') {
    issue(requirements, 'scene', field, 'Implement approved scene specification ' + block.sceneSpecKey +
      '; registry rendererKey is ' + value.id + '. Scene locales must be authored by Implement Scene.', 'Implement Scene');
    return { ...value, locales: {} };
  }
  if (block.type === 'code') {
    required(typeof spec.language === 'string' && (typeof spec.code === 'string' || typeof spec.fileLocation === 'string'),
      file, field + '.contentSpec', 'code requires canonical language and code or fileLocation');
    const { code, fileLocation, title } = spec;
    if (fileLocation && !safeAsset(root, fileLocation, file, field + '.contentSpec.fileLocation'))
      issue(requirements, 'media', field, 'Missing code file ' + fileLocation);
    return { ...value, language: spec.language,
      ...(code !== undefined ? { code: loc(code, language, file, field + '.contentSpec.code') } : {}),
      ...(fileLocation !== undefined ? { fileLocation: loc(fileLocation, language, file, field + '.contentSpec.fileLocation') } : {}),
      ...(title !== undefined ? { title: loc(title, language, file, field + '.contentSpec.title') } : {}) };
  }
  if (block.type === 'youtube') {
    required(typeof spec.href === 'string' && ['link', 'embed'].includes(spec.mode), file,
      field + '.contentSpec', 'youtube requires href and mode');
    required(spec.mode === 'link' || spec.title || spec.hint, file, field + '.contentSpec',
      'embedded YouTube requires title or hint');
    return { ...value, href: loc(spec.href, language, file, field + '.contentSpec.href'),
      mode: spec.mode,
      ...(spec.title ? { title: loc(spec.title, language, file, field + '.contentSpec.title') } : {}),
      ...(spec.hint ? { hint: loc(spec.hint, language, file, field + '.contentSpec.hint') } : {}) };
  }
  if (block.type === 'image') {
    const src = block.assetRequest?.path ?? spec.src;
    required(typeof src === 'string' && typeof spec.alt === 'string' &&
      ((Number.isFinite(spec.width) && Number.isFinite(spec.height)) ||
       (spec.fill === true && Number.isFinite(spec.aspectRatio))),
      file, field + '.contentSpec', 'image requires asset path, authored alt, and width/height or fill/aspectRatio');
    if (!safeAsset(root, src, file, field + '.assetRequest.path'))
      issue(requirements, 'media', field, 'Missing image asset ' + src, 'Media Production');
    return { ...value,
      ...(spec.fill === true ? { fill: true, aspectRatio: spec.aspectRatio, ...(spec.objectFit ? { objectFit: spec.objectFit } : {}) }
        : { width: spec.width, height: spec.height }),
      src: loc(src, language, file, field + '.assetRequest.path'),
      alt: loc(spec.alt, language, file, field + '.contentSpec.alt'),
      ...(spec.caption ? { caption: loc(spec.caption, language, file, field + '.contentSpec.caption') } : {}) };
  }
  if (block.type === 'audio' || block.type === 'video') {
    const src = block.assetRequest?.path ?? spec.fileLocation;
    required(typeof src === 'string', file, field + '.assetRequest.path', block.type + ' needs a fileLocation');
    if (!safeAsset(root, src, file, field + '.assetRequest.path'))
      issue(requirements, 'media', field, 'Missing ' + block.type + ' asset ' + src, 'Media Production');
    if (block.type === 'audio') {
      required(typeof spec.title === 'string', file, field + '.contentSpec.title', 'audio needs a title');
      return { ...value, fileLocation: loc(src, language, file, field + '.assetRequest.path'),
        title: loc(spec.title, language, file, field + '.contentSpec.title'),
        ...(spec.description ? { description: loc(spec.description, language, file, field + '.contentSpec.description') } : {}) };
    }
    required(typeof spec.poster === 'string', file, field + '.contentSpec.poster', 'video needs a poster');
    if (!safeAsset(root, spec.poster, file, field + '.contentSpec.poster'))
      issue(requirements, 'media', field, 'Missing poster asset ' + spec.poster, 'Media Production');
    return { ...value, fileLocation: loc(src, language, file, field + '.assetRequest.path'),
      poster: loc(spec.poster, language, file, field + '.contentSpec.poster'),
      ...(spec.title ? { title: loc(spec.title, language, file, field + '.contentSpec.title') } : {}) };
  }
  if (block.type === 'carousel') {
    required(Array.isArray(spec.slides) && spec.slides.length > 0,
      file, field + '.contentSpec.slides', 'carousel needs at least one typed slide');
    return { ...value, ...(spec.title ? { title: loc(spec.title, language, file, field + '.contentSpec.title') } : {}),
      slides: spec.slides.map((slide, index) => {
        const where = field + '.contentSpec.slides[' + index + ']';
        required(typeof slide.src === 'string' && typeof slide.alt === 'string',
          file, where, 'slide requires src and authored alt');
        if (!safeAsset(root, slide.src, file, where + '.src'))
          issue(requirements, 'media', where, 'Missing carousel asset ' + slide.src, 'Media Production');
        return { src: loc(slide.src, language, file, where + '.src'),
          alt: loc(slide.alt, language, file, where + '.alt'),
          ...(slide.caption ? { caption: loc(slide.caption, language, file, where + '.caption') } : {}) };
      }) };
  }
  fail(file, field + '.type', 'no unambiguous mapping from this editorial block to ContentBlock data: ' +
    block.type + '; add an approved typed contentSpec/contract mapping, never a placeholder');
}
function questionBlock(block, lessonId, language, root, requirements, field) {
  if (block.type === 'text')
    return { id: uuid5(lessonId, 'question-block/' + field), slug: 'text', type: 'text',
      value: loc(block.text, language, 'questions/questions.yaml', field + '.text') };
  const asset = block.assetPath;
  if (asset && !safeAsset(root, asset, 'questions/questions.yaml', field + '.assetPath'))
    issue(requirements, 'media', field, 'Missing Question image ' + asset, 'Media Production');
  fail('questions/questions.yaml', field,
    'Question image blocks lack required image layout and approved alt in the editorial schema; resolve contract mapping first');
}
function questionData(q, lessonId, language, root, requirements, index) {
  const p = 'questions[' + index + ']';
  const file = 'questions/questions.yaml';
  const blocks = (items, field) => items.map((item, i) =>
    questionBlock(item, lessonId, language, root, requirements, p + '.' + field + '[' + i + ']'));
  const data = {
    id: uuid5(lessonId, 'question/' + q.slug), slug: q.slug, type: q.type,
    assessmentMethod: q.assessmentMethod, restrictions: [],
    question: blocks(q.question, 'question'), explanation: blocks(q.explanation, 'explanation'),
    ...(q.hint ? { hint: blocks(q.hint, 'hint') } : {}),
  };
  const answer = q.answer;
  if (q.type === 'selectOneAnswer' || q.type === 'selectMultipleAnswers') {
    const answers = {};
    for (const kind of ['correct', 'incorrect', 'distractors']) {
      answers[kind] = {};
      for (const [i, choice] of answer[kind].entries()) {
        required(choice.content.length === 1, file, p + '.answer.' + kind + '[' + i + '].content',
          'canonical answer choice accepts exactly one ContentBlock');
        required(!Object.hasOwn(answers[kind], choice.key), file, p + '.answer.' + kind + '[' + i + '].key',
          'duplicate answer key');
        answers[kind][choice.key] = questionBlock(choice.content[0], lessonId, language, root, requirements,
          p + '.answer.' + kind + '[' + i + '].content[0]');
      }
    }
    return { ...data, answers };
  }
  if (q.type === 'matchBlocks') {
    const pairs = {};
    for (const [i, pair] of answer.pairs.entries()) {
      required(!Object.hasOwn(pairs, pair.key), file, p + '.answer.pairs[' + i + '].key', 'duplicate pair key');
      pairs[pair.key] = {
        left: questionBlock(pair.left, lessonId, language, root, requirements, p + '.answer.pairs[' + i + '].left'),
        right: questionBlock(pair.right, lessonId, language, root, requirements, p + '.answer.pairs[' + i + '].right'),
      };
    }
    return { ...data, pairs };
  }
  if (q.type === 'answerWithText')
    return { ...data, correctAnswers: answer.correctAnswers.map(text => loc(text, language, file, p + '.answer.correctAnswers')),
      placeholder: loc(answer.placeholder, language, file, p + '.answer.placeholder') };
  if (q.type === 'answerWithNumber')
    return { ...data, correctAnswers: answer.correctAnswers,
      placeholder: loc(answer.placeholder, language, file, p + '.answer.placeholder') };
  if (q.type === 'orderSequence') return { ...data, sequence: blocks(answer.sequence, 'answer.sequence') };
  if (q.type === 'buildAnswerWithBlocks')
    return { ...data, correctSequence: blocks(answer.correctSequence, 'answer.correctSequence'),
      distractors: blocks(answer.distractors, 'answer.distractors'),
      placeholder: loc(answer.placeholder, language, file, p + '.answer.placeholder') };
  if (q.type === 'fillBlanksWithBlocks')
    return { ...data, slots: answer.slots.map((slot, i) => ({
      selector: slot.selector, correctAnswer: questionBlock(slot.correctAnswer, lessonId, language, root, requirements,
        p + '.answer.slots[' + i + '].correctAnswer'),
    })), distractors: blocks(answer.distractors, 'answer.distractors'),
    placeholder: loc(answer.placeholder, language, file, p + '.answer.placeholder') };
  if (q.type === 'fillBlanksWithText')
    return { ...data, slots: answer.slots.map(slot => ({
      selector: slot.selector, correctAnswers: slot.correctAnswers.map(text =>
        loc(text, language, file, p + '.answer.slots.correctAnswers')),
    })), placeholder: loc(answer.placeholder, language, file, p + '.answer.placeholder') };
  fail(file, p + '.type', 'unsupported Question type ' + q.type);
}
function checkSources(root, content, questions, methodology) {
  const cf = 'content.yaml', qf = 'questions/questions.yaml', mf = content.methodologySource;
  required(content.lessonId === questions.lessonId, qf, 'lessonId', 'does not match content.yaml.lessonId');
  required(content.documentLanguage === questions.documentLanguage &&
    content.documentLanguage === methodology.documentLanguage, qf, 'documentLanguage', 'source language mismatch');
  required(sameList(content.supportedLanguages, questions.supportedLanguages) &&
    sameList(content.supportedLanguages, methodology.supportedLanguages), qf, 'supportedLanguages',
  'languages/order differ between approved sources');
  required(content.supportedLanguages.includes(content.documentLanguage), cf, 'supportedLanguages',
    'must include documentLanguage');
  required(content.status === 'approved' && questions.status === 'approved', cf, 'status',
    'Content and Question Bank must both be approved');
  required(questions.sources.methodology.path === content.methodologySource,
    qf, 'sources.methodology.path', 'must point to approved ' + content.methodologySource);
  required(questions.sources.content.path === 'content.yaml',
    qf, 'sources.content.path', 'must point to approved content.yaml');
  const plan = methodology.assessmentPlan.quizzes;
  unique(plan.map(x => x.key), mf, 'assessmentPlan.quizzes');
  const quizSections = content.sections.filter(s => s.type === 'quiz');
  unique(content.sections.map(s => s.key), cf, 'sections');
  unique(content.sections.flatMap(s => (s.blocks ?? []).map(b => s.key + '/' + b.key)), cf, 'sections.blocks');
  unique(content.sceneSpecifications.map(s => s.key), cf, 'sceneSpecifications');
  unique(questions.questions.map(q => q.slug), qf, 'questions');
  unique(questions.quizAssignments.map(q => q.assessmentPlanKey), qf, 'quizAssignments');
  required(methodology.assessmentPlan.quizRequired === (plan.length > 0), mf, 'assessmentPlan.quizRequired',
    'does not agree with assessmentPlan.quizzes');
  required(quizSections.length === plan.length && questions.quizAssignments.length === plan.length,
    cf, 'sections', 'Quiz Section count and Question assignments must match the Methodology assessment plan');
  const knownPlan = new Map(plan.map(q => [q.key, q]));
  const knownQuestions = new Map(questions.questions.map(q => [q.slug, q]));
  const assignments = new Map(questions.quizAssignments.map(q => [q.assessmentPlanKey, q]));
  for (const [i, section] of content.sections.entries()) {
    if (section.type !== 'quiz') continue;
    const p = 'sections[' + i + ']';
    const approved = knownPlan.get(section.assessmentPlanKey);
    required(approved, cf, p + '.assessmentPlanKey', 'unknown methodology Quiz key');
    const assigned = assignments.get(section.assessmentPlanKey);
    required(assigned, qf, 'quizAssignments', 'missing selection for ' + section.assessmentPlanKey);
    required(sameList(approved.targetSkills, section.targetSkills) &&
      sameList(approved.requiredAssessmentMethods, section.requiredAssessmentMethods),
      cf, p, 'Quiz Skills/Methods differ from approved Methodology assessmentPlan');
    const selected = assigned.selection.questionSlugs;
    unique(selected, qf, 'quizAssignments.' + section.assessmentPlanKey + '.selection.questionSlugs');
    if (assigned.selection.mode === 'sample')
      required(assigned.selection.count <= selected.length, qf, 'quizAssignments.' + section.assessmentPlanKey +
        '.selection.count', 'sample count exceeds selected pool');
    const presentMethods = new Set();
    const presentSkills = new Set();
    for (const slug of selected) {
      const q = knownQuestions.get(slug);
      required(q, qf, 'quizAssignments.' + section.assessmentPlanKey + '.selection.questionSlugs',
        'unknown Question slug ' + slug);
      required(q.assessmentPlanKeys.includes(section.assessmentPlanKey), qf, 'questions.' + slug +
        '.assessmentPlanKeys', 'Question is not assigned to this assessment plan');
      required(approved.requiredAssessmentMethods.includes(q.assessmentMethod), qf, 'questions.' + slug +
        '.assessmentMethod', 'method not approved for Quiz ' + section.assessmentPlanKey);
      required(q.targetSkills.every(id => approved.targetSkills.includes(id)), qf, 'questions.' + slug +
        '.targetSkills', 'Question references Skill outside Quiz plan');
      presentMethods.add(q.assessmentMethod);
      q.targetSkills.forEach(id => presentSkills.add(id));
    }
    for (const method of approved.requiredAssessmentMethods)
      required(presentMethods.has(method), qf, 'quizAssignments.' + section.assessmentPlanKey,
        'selected Quiz does not cover assessment method ' + method);
    for (const skill of approved.targetSkills)
      required(presentSkills.has(skill), qf, 'quizAssignments.' + section.assessmentPlanKey,
        'selected Quiz does not cover Skill ' + skill);
  }
  for (const assignment of questions.quizAssignments)
    required(knownPlan.has(assignment.assessmentPlanKey), qf, 'quizAssignments', 'unknown Quiz ' + assignment.assessmentPlanKey);
  const planKeys = new Set(plan.map(x => x.key));
  const allSkills = new Set(plan.flatMap(x => x.targetSkills));
  for (const [i, q] of questions.questions.entries()) {
    for (const key of q.assessmentPlanKeys)
      required(planKeys.has(key), qf, 'questions[' + i + '].assessmentPlanKeys', 'unknown assessment plan ' + key);
    q.targetSkills.forEach(id => allSkills.add(id));
  }
  for (const [i, coverage] of questions.coverage.entries()) {
    required(allSkills.has(coverage.targetSkill), qf, 'coverage[' + i + '].targetSkill',
      'coverage Skill not in lesson plan/question bank');
    for (const slug of coverage.questionSlugs)
      required(knownQuestions.has(slug), qf, 'coverage[' + i + '].questionSlugs', 'unknown Question ' + slug);
  }
  for (const [i, section] of content.sections.entries()) {
    for (const [j, block] of (section.blocks ?? []).entries()) {
      if (block.type !== 'scene') continue;
      const scene = content.sceneSpecifications.find(s => s.key === block.sceneSpecKey);
      required(scene, cf, 'sections[' + i + '].blocks[' + j + '].sceneSpecKey', 'unknown Scene specification');
      required(scene.status === 'approved', cf, 'sceneSpecifications.' + scene.key, 'Scene spec must be approved');
      required(fs.existsSync(path.join(root, scene.path)), cf, 'sceneSpecifications.' + scene.key + '.path',
        'Scene specification file is missing: ' + scene.path);
    }
  }
  return [...allSkills].sort();
}
function verifySkills(workspace, skills) {
  const root = path.join(workspace, 'data/skills');
  if (!skills.length) return;
  required(fs.existsSync(root), 'methodology.md', 'assessmentPlan', 'textbook has no Skill catalog');
  const known = new Set();
  function walk(dir) {
    noSymlinks(dir);
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isSymbolicLink()) throw new Error('Symlink in Skill catalog: ' + full);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile() && full.endsWith('.data.ts') && full.includes(path.sep + 'skills' + path.sep)) {
        const text = read(full);
        for (const match of text.matchAll(/\bid:\s*['"]([0-9a-f-]{36})['"]/g))
          if (exactUuid.test(match[1])) known.add(match[1]);
      }
    }
  }
  walk(root);
  for (const id of skills)
    required(known.has(id), 'methodology.md', 'assessmentPlan.targetSkills', 'unknown canonical Skill ID ' + id);
}
function targetFor(source, repo) {
  const absolute = path.resolve(source);
  noSymlinks(absolute);
  const rel = path.relative(repo, absolute).split(path.sep).join('/');
  const match = /^content\/((?:languages\/)?[a-z][a-z-]*)\/data\/lessons\/([0-9a-f])\/([0-9a-f-]{36})$/.exec(rel);
  if (!match || !exactUuid.test(match[3]) || match[3].slice(-1) !== match[2])
    throw new Error('Expected canonical content/<textbook>/data/lessons/<last-uuid-hex>/<uuid>: ' + rel);
  const workspace = path.join(repo, 'content', match[1]);
  required(fs.existsSync(path.join(workspace, 'package.json')), rel, '$', 'not a textbook workspace');
  return { root: absolute, workspace, lessonId: match[3] };
}
function inputFor(root) {
  const contentFile = path.join(root, 'content.yaml');
  const contentText = read(contentFile);
  const content = loadYAML(contentText, 'content.yaml');
  const methodologyFile = path.join(root, content.methodologySource ?? 'methodology.md');
  const methodologyText = read(methodologyFile);
  const methodology = loadMethodology(methodologyText, content.methodologySource ?? 'methodology.md');
  const questionText = read(path.join(root, 'questions/questions.yaml'));
  const questions = loadYAML(questionText, 'questions/questions.yaml');
  return { content, questions, methodology,
    inputs: { [content.methodologySource]: sha(methodologyText),
      'content.yaml': sha(contentText), 'questions/questions.yaml': sha(questionText) } };
}
function generateModel(target, input) {
  const { root, workspace, lessonId } = target;
  const { content, questions, methodology } = input;
  const requirements = [];
  const validators = schemaValidators();
  validateSchema(validators.methodology, methodology, content.methodologySource);
  validateSchema(validators.content, content, 'content.yaml');
  validateSchema(validators.questions, questions, 'questions/questions.yaml');
  required(content.lessonId === lessonId, 'content.yaml', 'lessonId', 'UUID differs from directory');
  const skills = checkSources(root, content, questions, methodology);
  verifySkills(workspace, skills);
  const language = content.documentLanguage;
  const bank = {};
  for (const [i, q] of questions.questions.entries()) {
    bank[q.type] ??= {};
    bank[q.type][q.slug] = questionData(q, lessonId, language, workspace, requirements, i);
  }
  const assignments = new Map(questions.quizAssignments.map(q => [q.assessmentPlanKey, q.selection]));
  const sections = content.sections.map((section, i) => {
    const base = { id: uuid5(lessonId, 'section/' + section.key), slug: section.key,
      type: section.type, title: sourceText(section.title, language),
      navigationLabel: sourceText(section.title, language) };
    if (section.type === 'quiz') {
      const selection = assignments.get(section.assessmentPlanKey);
      return { ...base, parameters: {
        selection, layout: { mode: 'stepper', showProgress: true },
        feedbackMode: 'after-completion',
        interaction: { retries: 0, showErrors: true, showCorrectAnswers: true,
          allowExplanations: true, allowDeferring: false,
          allowQuestionNavigation: true, skippable: false },
        results: { visibility: 'after-review', showScore: true }, screen: {},
      } };
    }
    return { ...base, content: section.blocks.map((b, j) =>
      blockData(b, lessonId, language, workspace, requirements,
        'sections[' + i + '].blocks[' + j + ']')) };
  });
  for (const [i, d] of content.productionDependencies.entries())
    if (d.status !== 'ready') issue(requirements, d.kind, 'productionDependencies[' + i + ']', d.description, d.owner);
  for (const [i, d] of questions.unresolvedDependencies.entries())
    issue(requirements, d.kind, 'questions.unresolvedDependencies[' + i + ']', d.description);
  for (const [i, scene] of content.sceneSpecifications.entries())
    if (!content.sections.some(s => (s.blocks ?? []).some(b => b.sceneSpecKey === scene.key)))
      issue(requirements, 'scene', 'sceneSpecifications[' + i + ']',
        'Unused Scene specification ' + scene.key + ' needs editorial reconciliation');
  if (content.supportedLanguages.some(code => code !== language))
    issue(requirements, 'localization', 'supportedLanguages',
      'Translation Production must supply ' + content.supportedLanguages.filter(code => code !== language).join(', '));
  issue(requirements, 'contract', 'flashcards',
    'Flashcards YAML -> canonical Flashcard contract integration deferred until the parallel contract is approved');
  return { bank, sections, skills, requirements };
}
function renderLesson(input, model) {
  const content = input.content;
  const languages = JSON.stringify(content.supportedLanguages);
  const bank = JSON.stringify(model.bank, null, 2);
  const parts = model.sections.map(section => {
    if (section.type === 'quiz')
      return 'createSection<Languages>()(' + JSON.stringify(section, null, 2) + ')';
    const { content: blocks, ...meta } = section;
    return 'createSection<Languages>()({ ...(' + JSON.stringify(meta, null, 2) + ' as const)' +
      ', content: [' + blocks.map(block => 'createContentBlock<Languages>()(' +
        JSON.stringify(block, null, 2) + ')').join(',\n') + '] })';
  });
  return marker + '\n' +
    "import { createLesson, createSection, createContentBlock } from '@svitlo/engine/builders';\n" +
    "import type { Locale_Languages, Question_Catalog } from '@svitlo/contracts/content';\n\n" +
    'export const supportedLanguages = ' + languages + ' as const satisfies Locale_Languages;\n' +
    'export type Languages = typeof supportedLanguages;\n' +
    'export const questionBank = ' + bank + " satisfies Question_Catalog<'data', Languages>;\n" +
    'export const lessonCreator = createLesson<Languages>()({\n' +
    '  id: ' + JSON.stringify(content.lessonId) + ',\n' +
    '  slug: ' + JSON.stringify(content.lessonSlug) + ',\n' +
    '  title: ' + JSON.stringify(sourceText(content.title, content.documentLanguage)) + ',\n' +
    '  flashcards: [],\n' +
    '  skills: ' + JSON.stringify(model.skills) + ',\n' +
    '  parameters: { requireQuiz: ' + content.sections.some(s => s.type === 'quiz') +
    ', languages: supportedLanguages, sections: { allowNavigation: true, allowSkipping: true, showIndexes: true } },\n' +
    '  questions: questionBank,\n' +
    '  sections: [\n' + parts.map(p => '    ' + p + ',').join('\n') + '\n  ],\n' +
    '});\n' +
    'export const lessonData = lessonCreator.getData();\n';
}
function requirementFiles(input, requirements) {
  const name = input.content.lessonId;
  const json = JSON.stringify({ version: 1, lessonId: name, sourceLanguage: input.content.documentLanguage,
    supportedLanguages: input.content.supportedLanguages, unresolved: requirements }, null, 2) + '\n';
  const md = '# Lesson ' + name + ' — Builder handoff\n\n' +
    'Generated from approved editorial YAML. This is not Scene or Media implementation.\n\n' +
    (requirements.length ? requirements.map(r =>
      '- **' + r.kind + '** (' + r.location + '): ' + r.detail +
      (r.owner ? ' — owner: ' + r.owner : '')).join('\n') : 'No unresolved requirements.') + '\n';
  return { 'requirements.json': json, 'requirements.md': md };
}
function safeWrite(file, value) {
  noSymlinks(file);
  if (fs.existsSync(file) && read(file) === value) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const temporary = file + '.tmp-' + process.pid;
  try {
    fs.writeFileSync(temporary, value, { flag: 'wx' });
    fs.renameSync(temporary, file);
  } finally {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
  }
  return true;
}
function ownedFiles(target, files, mode, sourceHashes, slug) {
  const output = path.join(target.root, 'generated');
  const entryName = slug + '.data.ts';
  const entryFile = path.join(target.root, entryName);
  const entryText = marker + '\nexport { lessonData } from "./generated/lesson.data";\n';
  const manifestFile = path.join(output, 'manifest.json');
  const old = fs.existsSync(manifestFile) ? JSON.parse(read(manifestFile)) : null;
  const otherEntries = fs.readdirSync(target.root).filter(name => name.endsWith('.data.ts') && name !== entryName);
  required(otherEntries.length === 0, 'generated/manifest.json', 'entrypoint',
    'existing authored Lesson entrypoint(s) must not be duplicated: ' + otherEntries.join(', '));
  if (old) {
    required(old.version === 1 && old.lessonId === target.lessonId && old.generator === 'lesson-builder-v1',
      'generated/manifest.json', '$', 'invalid ownership manifest');
    required(old.entrypoint?.name === entryName, 'generated/manifest.json', 'entrypoint',
      'Lesson slug changed; manually migrate the existing entrypoint');
    for (const [name, hash] of Object.entries(old.outputs)) {
      required(['lesson.data.ts', 'requirements.json', 'requirements.md'].includes(name),
        'generated/manifest.json', 'outputs', 'unrecognized generated path ' + name);
      const existing = path.join(output, name);
      if (fs.existsSync(existing))
        required(sha(read(existing)) === hash, name, '$', 'generated output modified manually; preserve changes before regeneration');
    }
    if (fs.existsSync(entryFile))
      required(sha(read(entryFile)) === old.entrypoint.sha256, entryName, '$',
        'generated entrypoint modified manually; preserve changes before regeneration');
  } else {
    required(!fs.existsSync(entryFile), entryName, '$',
      'unowned Lesson entrypoint exists; refusing overwrite');
  }
  const manifest = JSON.stringify({
    version: 1, generator: 'lesson-builder-v1', lessonId: target.lessonId,
    inputs: sourceHashes, checks: ['json-schema-2020-12', 'cross-file', 'skill-catalog', 'asset-paths'],
    entrypoint: { name: entryName, sha256: sha(entryText) },
    outputs: Object.fromEntries(Object.entries(files).map(([name, value]) => [name, sha(value)])),
  }, null, 2) + '\n';
  const expected = { ...files, 'manifest.json': manifest };
  let changed = 0;
  for (const [file, name, value] of [
    ...Object.entries(files).map(([name, value]) => [path.join(output, name), 'generated/' + name, value]),
    [entryFile, entryName, entryText],
  ]) {
    if (!fs.existsSync(file) || read(file) !== value) {
      if (mode === 'check') fail(name, '$', 'missing/stale generated file');
      if (!old && fs.existsSync(file))
        fail(name, '$', 'unowned output exists; refusing overwrite');
      if (safeWrite(file, value)) changed++;
    }
  }
  if (!fs.existsSync(manifestFile) || read(manifestFile) !== manifest) {
    if (mode === 'check') fail('generated/manifest.json', '$', 'missing/stale generated file');
    if (safeWrite(manifestFile, manifest)) changed++;
  }
  return { changed, files: [entryName, ...Object.keys(expected).map(name => 'generated/' + name)] };
}
export function runOne(source, mode = 'check', repo = repoRoot) {
  if (!['check', 'generate'].includes(mode)) throw new Error('Mode must be check or generate');
  const target = targetFor(source, repo);
  const input = inputFor(target.root);
  // Validation is a fail-closed, read-only phase: invalid inputs never write partial output.
  const model = generateModel(target, input);
  const files = { 'lesson.data.ts': renderLesson(input, model),
    ...requirementFiles(input, model.requirements) };
  const output = ownedFiles(target, files, mode, input.inputs, input.content.lessonSlug);
  return { ...output, requirements: model.requirements, lessonId: target.lessonId };
}
function discover(repo) {
  const roots = [];
  const content = path.join(repo, 'content');
  for (const entry of fs.readdirSync(content, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const folder = path.join(content, entry.name);
    const candidates = entry.name === 'languages'
      ? fs.readdirSync(folder, { withFileTypes: true }).filter(e => e.isDirectory()).map(e => path.join(folder, e.name))
      : [folder];
    for (const workspace of candidates) {
      const lessons = path.join(workspace, 'data/lessons');
      if (!fs.existsSync(lessons)) continue;
      for (const bucket of fs.readdirSync(lessons, { withFileTypes: true })) {
        if (!bucket.isDirectory() || !/^[0-9a-f]$/.test(bucket.name)) continue;
        for (const entity of fs.readdirSync(path.join(lessons, bucket.name), { withFileTypes: true })) {
          if (!entity.isDirectory()) continue;
          const folder = path.join(lessons, bucket.name, entity.name);
          if (fs.existsSync(path.join(folder, 'content.yaml'))) roots.push(folder);
        }
      }
    }
  }
  return roots.sort();
}
export function main(args = process.argv.slice(2), repo = repoRoot) {
  const mode = args.shift();
  if (!['generate', 'check'].includes(mode) || (args.length && !(args.length === 2 && args[0] === '--source'))) {
    throw new Error('Usage: node scripts/lesson-builder.mjs generate|check [--source content/<book>/data/lessons/<bucket>/<uuid>]');
  }
  const roots = args.length ? [path.resolve(repo, args[1])] : discover(repo);
  for (const source of roots) {
    const result = runOne(source, mode, repo);
    console.log(result.lessonId + ': ' + (mode === 'check' ? 'up to date' :
      result.changed + ' files written') + '; unresolved: ' + result.requirements.length);
  }
  console.log('Verified ' + roots.length + ' editorial Lesson source(s)');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
