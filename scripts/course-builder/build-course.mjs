#!/usr/bin/env node
/**
 * Deterministic Course editorial TOC -> typed Course composition.
 *
 * The editorial schema does not contain publishable Course title/description or
 * translations. This generator therefore exports a typed composition factory,
 * never a fake publishable Course or invented translation.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import Ajv2020 from 'ajv/dist/2020.js';
import ts from 'typescript';

const repoRoot = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
const UUID = /^[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}$/;
const PACKAGE = /^content\/[a-z][a-z0-9-]*$/;
const generatedHeader = '// GENERATED BY scripts/course-builder/build-course.mjs; DO NOT EDIT.\n';

function error(code, message) {
  throw new Error('Course Builder [' + code + ']: ' + message);
}

function parseYaml(text, filename) {
  const document = YAML.parseDocument(text, { strict: true, uniqueKeys: true });
  if (document.errors.length) error('YAML', filename + ': ' + document.errors.map(x => x.message).join('; '));
  return document.toJS({ maxAliasCount: 0 });
}

function methodologyFrontmatter(text) {
  const match = /^---\s*\r?\n([\s\S]*?)\r?\n---(?:\s*\r?\n|$)/.exec(text);
  if (!match) error('METHODOLOGY', 'methodology.md must contain YAML frontmatter');
  const data = parseYaml(match[1], 'methodology.md');
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    error('METHODOLOGY', 'invalid frontmatter');
  }
  return data;
}

/** Stable technical UUIDv5 derived from a Course UUID and an immutable TOC key. */
export function groupUuid(courseId, kind, key) {
  if (!UUID.test(courseId)) error('UUID', 'invalid Course UUID ' + courseId);
  const ns = Buffer.from(courseId.replaceAll('-', ''), 'hex');
  const bytes = createHash('sha1')
    .update(ns)
    .update(kind + ':' + key)
    .digest()
    .subarray(0, 16);
  bytes[6] = (bytes[6] & 0x0f) | 0x50;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = bytes.toString('hex');
  return [hex.slice(0, 8), hex.slice(8, 12), hex.slice(12, 16), hex.slice(16, 20), hex.slice(20)].join('-');
}

function checkedLanguages(input, label, supportedCodes) {
  if (!Array.isArray(input) || input.length === 0 || input.some(x => !supportedCodes.has(x))) {
    error('LANGUAGES', label + ' contains an unsupported or empty language list: ' + JSON.stringify(input));
  }
  if (new Set(input).size !== input.length) error('LANGUAGES', label + ' contains duplicate languages');
  return input;
}

function validateSchema(plan, schema) {
  const ajv = new Ajv2020({ allErrors: true, strict: false });
  const validate = ajv.compile(schema);
  if (!validate(plan)) {
    error('SCHEMA', (validate.errors ?? []).map(x => x.instancePath + ' ' + x.message).join('; '));
  }
}

function normalizeTree(items, courseId, seenKeys, lessonIds, breadcrumb = 'content') {
  return items.map(node => {
    const location = breadcrumb + '/' + node.key;
    if (seenKeys.has(node.key)) error('DUPLICATE_KEY', location + ': repeated key ' + node.key);
    seenKeys.add(node.key);
    if (node.type === 'lesson') {
      if (!node.lessonId) error('UNMATCHED_LESSON', location + ': missing matched lessonId');
      if (!UUID.test(node.lessonId)) error('UUID', location + ': invalid Lesson UUID ' + node.lessonId);
      lessonIds.add(node.lessonId);
      return { type: 'lesson', key: node.key, lessonId: node.lessonId, title: node.title };
    }
    if (node.type !== 'module' && node.type !== 'chapter') {
      error('NESTING', location + ': unsupported node ' + node.type);
    }
    return {
      type: node.type,
      key: node.key,
      id: groupUuid(courseId, node.type, node.key),
      title: node.title,
      children: normalizeTree(node.children, courseId, seenKeys, lessonIds, location),
    };
  });
}

/**
 * Pure editorial validation + externally injected Lesson resolution.
 * The resolver must return actual implemented Lesson data metadata and import
 * coordinates; it must never manufacture an unimplemented Lesson.
 */
export async function buildCoursePlan({ methodologyText, tocText, schema, supportedCodes, resolveLesson }) {
  const methodology = methodologyFrontmatter(methodologyText);
  const toc = parseYaml(tocText, 'toc.yaml');
  validateSchema(toc, schema);
  if (methodology.kind !== 'course-methodology' || methodology.schemaVersion !== 1) {
    error('METHODOLOGY', 'unknown methodology format');
  }
  if (methodology.status !== 'approved' || toc.status !== 'approved') {
    error('APPROVAL', 'both methodology.md and toc.yaml must be approved');
  }
  if (!UUID.test(methodology.courseId) || methodology.courseId !== toc.courseId) {
    error('COURSE_ID', 'methodology.md and toc.yaml Course UUIDs differ or are malformed');
  }
  const languages = checkedLanguages(toc.supportedLanguages, 'TOC', supportedCodes);
  checkedLanguages(methodology.supportedLanguages, 'Methodology', supportedCodes);
  if (JSON.stringify(languages) !== JSON.stringify(methodology.supportedLanguages)) {
    error('LANGUAGES', 'TOC supportedLanguages must match ordered Methodology supportedLanguages');
  }
  if (!languages.includes(toc.documentLanguage)) {
    error('LANGUAGES', 'TOC documentLanguage ' + toc.documentLanguage + ' is not a Course supported language');
  }
  const lessonIds = new Set();
  const tree = normalizeTree(toc.content, toc.courseId, new Set(), lessonIds);
  const lessons = new Map();
  for (const id of lessonIds) {
    const item = await resolveLesson(id);
    if (!item) error('MISSING_LESSON', id + ' has no implemented standalone Lesson Data');
    if (item.id !== id) error('LESSON_ID', id + ': resolved Lesson Data declares ' + item.id);
    const actual = checkedLanguages(item.languages, 'Lesson ' + id, supportedCodes);
    const missing = languages.filter(code => !actual.includes(code));
    if (missing.length) error('LESSON_LOCALES', id + ': missing Course locales ' + missing.join(', '));
    // The current Course<'data', L> expects exactly L on nested Lesson Data.
    // An actual superset is semantically valid, but cannot safely be cast to L.
    if (JSON.stringify(actual) !== JSON.stringify(languages)) {
      error(
        'TYPED_LANGUAGE_SUPERSET',
        id +
          ': Lesson languages (' +
          actual.join(', ') +
          ') cover Course languages (' +
          languages.join(', ') +
          '), but Course creator currently requires an identical tuple',
      );
    }
    if (!item.source || !item.exportName) error('LESSON_EXPORT', id + ': no unique exported Lesson Data symbol');
    lessons.set(id, item);
  }
  return { courseId: toc.courseId, documentLanguage: toc.documentLanguage, languages, tree, lessons };
}

function titleKey(node) {
  return node.type + '/' + node.key;
}
function flattenGroups(items) {
  return items.flatMap(item => (item.type === 'lesson' ? [] : [item, ...flattenGroups(item.children)]));
}
function flattenSlots(items) {
  return items.flatMap(item => (item.type === 'lesson' ? [item] : flattenSlots(item.children)));
}
function titleSource(title) {
  return typeof title === 'string' ? title : title.value;
}
const js = value => JSON.stringify(value);

/**
 * A compile-time strict factory. Missing translations cannot be passed to
 * CourseLocalizedGroupTitles; intentional invariant titles use scalar values.
 * Frontend Course title/description must be supplied from a separately approved
 * source (the Methodology does not authorize deriving frontend copy).
 */
export function renderCourseSource(plan, outputFilename) {
  const groups = flattenGroups(plan.tree);
  const localized = groups.filter(node => typeof node.title === 'string');
  const lessons = [...plan.lessons.values()];
  const importLines = lessons.map((item, index) => {
    let relative = path.relative(path.dirname(outputFilename), item.source).split(path.sep).join('/');
    relative = relative.replace(/\.ts$/, '');
    if (!relative.startsWith('.')) relative = './' + relative;
    return 'import { ' + item.exportName + ' as lesson' + index + ' } from ' + js(relative) + ';';
  });
  const lessonVars = new Map(lessons.map((item, index) => [item.id, 'lesson' + index]));
  const groupTitle = node => {
    const value = typeof node.title === 'string' ? 'titles[' + js(titleKey(node)) + ']' : js(node.title.value);
    const uuid = groupUuid(plan.courseId, node.type + '-title', node.key);
    return '{ id: ' + js(uuid) + ', slug: ' + js('title-' + node.key) + ', type: "text", value: ' + value + ' }';
  };
  const emitNode = (node, indent = '    ') => {
    if (node.type === 'lesson') return indent + lessonVars.get(node.lessonId);
    const creator = node.type === 'module' ? 'createModule' : 'createChapter';
    const children = node.children.map(child => emitNode(child, indent + '    ')).join(',\n');
    return [
      indent + creator + '<CourseLanguages>({',
      indent + '  type: ' + js(node.type) + ',',
      indent + '  id: ' + js(node.id) + ',',
      indent + '  title: ' + groupTitle(node) + ',',
      indent + '  content: [',
      children,
      indent + '  ],',
      indent + '}).getData()',
    ].join('\n');
  };
  const entries = plan.tree.map(node => emitNode(node)).join(',\n');
  const keys = localized.map(node => '  ' + js(titleKey(node)) + ': Record<CourseLanguage, string>;').join('\n');
  const sources = localized
    .map(
      node =>
        '  ' + js(titleKey(node)) + ': { ' + js(plan.documentLanguage) + ': ' + js(titleSource(node.title)) + ' },',
    )
    .join('\n');
  const slotSources = flattenSlots(plan.tree)
    .map(
      node =>
        '  ' +
        js(node.key) +
        ': { lessonId: ' +
        js(node.lessonId) +
        ', ' +
        'documentLanguage: ' +
        js(plan.documentLanguage) +
        ', title: ' +
        js(titleSource(node.title)) +
        ' },',
    )
    .join('\n');
  return [
    generatedHeader.trimEnd(),
    'import { createCourse, createChapter, createModule } from "@svitlo/engine/builders";',
    'import type { Course, Locale_Languages } from "@svitlo/engine/content";',
    ...importLines,
    '',
    'export const courseLanguages = ' + js(plan.languages) + ' as const satisfies Locale_Languages;',
    'export type CourseLanguages = typeof courseLanguages;',
    'export type CourseLanguage = CourseLanguages[number];',
    '',
    '/** Only Course-owned grouping titles; Lesson navigation uses canonical Lesson titles. */',
    'export type CourseLocalizedGroupTitles = {',
    keys,
    '};',
    '/** The actual source-language text, never replicated into other locales. */',
    'export const courseGroupTitleSources = {',
    sources,
    '} as const satisfies { [K in keyof CourseLocalizedGroupTitles]: Partial<CourseLocalizedGroupTitles[K]> };',
    '/** Planned Lesson slot labels are editorial; they are not Lesson title overrides. */',
    'export const courseLessonSlotTitleSources = {',
    slotSources,
    '} as const;',
    '',
    'export type CourseFrontendMetadata = Pick<',
    '  Course<"data", CourseLanguages>,',
    '  "title" | "description" | "scenarioMode" | "prerequisites"',
    '>;',
    '',
    'export function createCourseData(metadata: CourseFrontendMetadata, titles: CourseLocalizedGroupTitles) {',
    '  return createCourse<CourseLanguages>({',
    '    type: "course",',
    '    id: ' + js(plan.courseId) + ',',
    '    parameters: { languages: courseLanguages },',
    '    ...metadata,',
    '    content: [',
    entries,
    '    ],',
    '  }).getData();',
    '}',
    '',
  ].join('\n');
}

function lessonExport(source, filename) {
  const ast = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const names = [];
  for (const statement of ast.statements) {
    if (!ts.isVariableStatement(statement) || !statement.modifiers?.some(x => x.kind === ts.SyntaxKind.ExportKeyword))
      continue;
    for (const declaration of statement.declarationList.declarations) {
      if (ts.isIdentifier(declaration.name) && /_Data$/.test(declaration.name.text)) {
        names.push(declaration.name.text);
      }
    }
  }
  if (names.length !== 1) error('LESSON_EXPORT', filename + ': expected one exported *_Data variable');
  return names[0];
}

export async function resolveImplementedLesson(root, id) {
  const { resolveEntityPath, loadLessonData } = await import('@svitlo/engine/utils');
  const folder = path.join(root, 'data/lessons', resolveEntityPath(id));
  if (!fs.existsSync(folder)) {
    error('MISSING_LESSON', id + ': expected implemented Lesson *.data.ts at ' + folder);
  }
  const candidates = fs
    .readdirSync(folder)
    .filter(name => name.endsWith('.data.ts'))
    .sort();
  if (candidates.length !== 1) {
    error(
      'MISSING_LESSON',
      id + ': expected exactly one Lesson *.data.ts at ' + folder + ' (found ' + candidates.length + ')',
    );
  }
  const filename = path.join(folder, candidates[0]);
  const lesson = await loadLessonData(filename);
  return {
    id: lesson.id,
    languages: lesson.parameters?.languages,
    source: filename,
    exportName: lessonExport(fs.readFileSync(filename, 'utf8'), filename),
  };
}

/** Ownership-safe idempotent output; --check never creates or changes files. */
export function verifyOrWriteGenerated(filename, rendered, action) {
  if (action !== '--write' && action !== '--check') error('ARGS', 'unknown output action ' + action);
  const existing = fs.existsSync(filename) ? fs.readFileSync(filename, 'utf8') : undefined;
  if (action === '--check') {
    if (existing !== rendered) error('STALE', 'Course TS composition is absent or out of date: ' + filename);
    return false;
  }
  if (existing !== undefined && !existing.startsWith(generatedHeader)) {
    error('OWNERSHIP', 'refusing to replace non-generated ' + filename);
  }
  if (existing === rendered) return false;
  fs.writeFileSync(filename, rendered, 'utf8');
  return true;
}

export function parseArguments(args) {
  let packagePath, courseId, action;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--package') packagePath = args[++i];
    else if (args[i] === '--course') courseId = args[++i];
    else if (args[i] === '--write' || args[i] === '--check') {
      if (action) error('ARGS', 'select one action');
      action = args[i];
    } else error('ARGS', 'unexpected argument ' + args[i]);
  }
  if (!PACKAGE.test(packagePath ?? '') || !UUID.test(courseId ?? '') || !action) {
    error(
      'ARGS',
      'usage: node scripts/course-builder/build-course.mjs --package content/<book> --course <uuid> --write|--check',
    );
  }
  return { packagePath, courseId, action };
}

export async function main(args) {
  const { packagePath, courseId, action } = parseArguments(args);
  const root = path.join(repoRoot, packagePath);
  const { resolveEntityPath } = await import('@svitlo/engine/utils');
  const { DEFAULT_SUPPORTED_LANGUAGES } = await import('@svitlo/contracts/localization');
  const folder = path.join(root, 'data/courses', resolveEntityPath(courseId));
  const methodology = path.join(folder, 'methodology.md');
  const toc = path.join(folder, 'toc.yaml');
  if (!fs.existsSync(methodology) || !fs.existsSync(toc)) {
    error('INPUT', 'missing ' + (!fs.existsSync(methodology) ? methodology : toc));
  }
  const schema = JSON.parse(
    fs.readFileSync(path.join(repoRoot, 'studio/skills/course-workflow/course-toc.schema.json'), 'utf8'),
  );
  const plan = await buildCoursePlan({
    methodologyText: fs.readFileSync(methodology, 'utf8'),
    tocText: fs.readFileSync(toc, 'utf8'),
    schema,
    supportedCodes: new Set(DEFAULT_SUPPORTED_LANGUAGES.map(x => x.language)),
    resolveLesson: id => resolveImplementedLesson(root, id),
  });
  if (plan.courseId !== courseId) error('COURSE_ID', 'requested Course UUID differs from editorial input');
  const filename = path.join(folder, 'toc.generated.ts');
  const rendered = renderCourseSource(plan, filename);
  const updated = verifyOrWriteGenerated(filename, rendered, action);
  if (action === '--write' && !updated) return console.log('Course TS already up to date: ' + filename);
  console.log(
    'Validated Course ' + plan.courseId + ' (' + plan.lessons.size + ' unique Lessons); ' + action + ' ' + filename,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch(cause => {
    console.error(cause.message);
    process.exitCode = 1;
  });
}
