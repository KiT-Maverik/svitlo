#!/usr/bin/env node
/**
 * Canonical Scene Registry generator for Scene-enabled textbook packages.
 * Keep relative, statically analyzable imports in each textbook's sceneLoader.ts.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { resolveEntityPath } from '@svitlo/engine/build';

const repoRoot = resolve(fileURLToPath(new URL('../..', import.meta.url)));

/** Run with an explicit textbook root to support isolated generator tests. */
export async function syncSceneRegistry(root, mode, packageName = 'the selected textbook') {
  const scenes = join(root, 'scenes');
  const entries = readdirSync(scenes, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .flatMap(bucket => {
      if (!/^[0-9a-f]$/.test(bucket.name)) throw new Error('Invalid Scene bucket: ' + bucket.name);
      return readdirSync(join(scenes, bucket.name), { withFileTypes: true })
        .filter(entry => entry.isDirectory())
        .map(entry => {
          const path = resolveEntityPath(entry.name);
          if (path !== `${bucket.name}/${entry.name}`) throw new Error('Scene directory must match UUID path: ' + path);
          return { id: entry.name, path: `./${path}` };
        });
    })
    .sort((a, b) => a.id.localeCompare(b.id));
  if (!entries.length || new Set(entries.map(entry => entry.id)).size !== entries.length) {
    throw new Error('Scene registry needs unique authored Scene directories');
  }
  for (const entry of entries) readFileSync(join(scenes, entry.path, 'index.ts'), 'utf8');
  const imports = entries
    .map(
      entry =>
        `  '${entry.id}': () =>\n    import('${entry.path}').then(mod => ({ default: mod.default as unknown as SceneComponent })),`,
    )
    .join('\n');
  const output =
    `// Generated by scripts/textbook-tooling/generate-scenes.mjs. Run npm run content:generate:scenes after adding a Scene.\n` +
    `import type { SceneRegistry } from '@svitlo/ui-kit';\n` +
    `import { createSceneRegistry, type SceneModule } from './createSceneRegistry';\n\n` +
    `type SceneComponent = NonNullable<ReturnType<SceneRegistry>>;\n\n` +
    `const sceneImports: Readonly<Record<string, () => Promise<SceneModule>>> = {\n${imports}\n};\n\n` +
    `const registry = createSceneRegistry(sceneImports);\n` +
    `export const preloadScene: (id: string) => Promise<void> = registry.preloadScene;\n` +
    `export const resolveScene: SceneRegistry = registry.resolveScene;\n`;
  const target = join(scenes, 'sceneLoader.ts');
  // Match the same Prettier rules applied by the Ready-for-Review PR formatter.
  // Without this, auto-formatting makes a valid generated registry appear stale.
  const formatted = await format(output, { ...(await resolveConfig(target)), filepath: target });
  if (mode === '--write') writeFileSync(target, formatted);
  else if (mode === '--check') {
    if (readFileSync(target, 'utf8') !== formatted)
      throw new Error('Stale Scene registry; run npm run content:generate:scenes --workspace ' + packageName);
  } else throw new Error('Usage: generate-scenes.mjs --write|--check');

  return entries.length;
}

/** The CLI runs in a textbook workspace; it never guesses the active package. */
async function cli() {
  const root = resolve(process.cwd());
  const packagePath = relative(repoRoot, root).split(sep).join('/');
  const name = root.split(sep).at(-1);
  if (!/^content\/(?:[a-z][a-z-]*|languages\/[a-z][a-z-]*)$/.test(packagePath)) {
    throw new Error('Run Scene generation from a content textbook workspace');
  }
  const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  if (manifest.name !== '@svitlo/' + name || !manifest.exports?.['./scenes']) {
    throw new Error('Textbook must declare its public Scene export: ' + packagePath);
  }
  const count = await syncSceneRegistry(root, process.argv[2], manifest.name);
  console.log('Verified ' + count + ' statically registered Scenes in ' + manifest.name);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  cli().catch(error => {
    console.error(error);
    process.exitCode = 1;
  });
}
