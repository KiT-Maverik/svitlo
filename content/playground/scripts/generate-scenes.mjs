#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const scenes = join(root, 'src/components/scenes');
const entries = readdirSync(scenes, { withFileTypes: true })
  .filter(entry => entry.isDirectory() && /^[a-z]$/.test(entry.name))
  .flatMap(letter => readdirSync(join(scenes, letter.name), { withFileTypes: true })
    .filter(entry => entry.isDirectory() && /^[a-z][a-z0-9-]+$/.test(entry.name))
    .map(entry => ({ id: entry.name, path: `./${letter.name}/${entry.name}` })))
  .sort((a, b) => a.id.localeCompare(b.id));
if (!entries.length || new Set(entries.map(entry => entry.id)).size !== entries.length) {
  throw new Error('Scene registry needs unique authored Scene directories');
}
for (const entry of entries) readFileSync(join(scenes, entry.path, 'index.ts'), 'utf8');
const imports = entries.map(entry =>
  `  '${entry.id}': () =>\n    import('${entry.path}').then(mod => ({ default: mod.default as unknown as SceneComponent })),`)
  .join('\n');
const output = `// Generated by scripts/generate-scenes.mjs. Run npm run generate:scenes after adding a Scene.\n` +
`import { lazy } from 'react';\n` +
`import type { SceneRegistry } from '@svitlo/ui-kit/widgets';\n\n` +
`type SceneComponent = NonNullable<ReturnType<SceneRegistry>>;\n` +
`type SceneModule = { default: SceneComponent };\n\n` +
`const sceneImports: Readonly<Record<string, () => Promise<SceneModule>>> = {\n${imports}\n};\n\n` +
`const cache = new Map<string, SceneComponent>();\n\n` +
`export const resolveScene: SceneRegistry = id => {\n` +
`  const load = sceneImports[id];\n` +
`  if (!load) return undefined;\n` +
`  let component = cache.get(id);\n` +
`  if (!component) {\n` +
`    component = lazy(load);\n` +
`    cache.set(id, component);\n` +
`  }\n` +
`  return component;\n` +
`};\n`;
const target = join(scenes, 'sceneLoader.ts');
if (process.argv[2] === '--write') writeFileSync(target, output);
else if (process.argv[2] === '--check') {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Stale Scene registry; run npm run generate:scenes --workspace @svitlo/playground');
} else throw new Error('Usage: generate-scenes.mjs --write|--check');
console.log(`Verified ${entries.length} statically registered Scenes`);
