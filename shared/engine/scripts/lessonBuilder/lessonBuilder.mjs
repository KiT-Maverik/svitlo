#!/usr/bin/env node
/**
 * @fileoverview Lesson YAML -> TypeScript draft scaffolder.
 *
 * This build-time script saves AI authoring tokens by emitting mechanically
 * authored define* calls. Its output is a draft, not publishable Lesson Props:
 * missing fields and translations are deliberately left for the AI editor and
 * normal TypeScript diagnostics. No approvals, schemas, content checks,
 * TypeScript typechecks, asset resolution, or publication run here.
 *
 * Polymorphic children require type for factory dispatch. The only dispatch
 * table is Engine's yamlFactoryByType.ts (read as TypeScript syntax, not
 * executed or validated). Output contains only the source documentLanguage's
 * authored locale values; other languages are never invented.
 *
 * The separate generateLessonProps publisher is not invoked by this script.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import yaml from 'yaml';
import { loadFactoryRegistry } from '../yamlDraft/loadFactoryRegistry.mjs';
export { loadFactoryRegistry };

export const repoRoot = path.resolve(fileURLToPath(new URL('../../../..', import.meta.url)));
const header = '// Generated by shared/engine/scripts/lessonBuilder/lessonBuilder.mjs; DRAFT, DO NOT EDIT.\n';
const checksumLabel = '// Draft content sha256: ';
const uuidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

export class BuilderDiagnostic extends Error {
  constructor(file, field, message) {
    super(file + ':' + field + ': ' + message);
    this.name = 'BuilderDiagnostic';
    this.file = file;
    this.field = field;
  }
}

function fail(file, field, message) {
  throw new BuilderDiagnostic(file, field, message);
}

const isRecord = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const digest = text => crypto.createHash('sha256').update(text).digest('hex');

function noSymlinks(location) {
  let current = path.parse(path.resolve(location)).root;
  for (const segment of path.resolve(location).slice(current.length).split(path.sep).filter(Boolean)) {
    current = path.join(current, segment);
    try {
      if (fs.lstatSync(current).isSymbolicLink()) throw new Error('Refusing symlink: ' + current);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
}

function parseYaml(file, relative) {
  noSymlinks(file);
  let document;
  try {
    document = yaml.parseDocument(fs.readFileSync(file, 'utf8'), {
      strict: true,
      uniqueKeys: true,
      version: '1.2',
    });
    if (document.errors.length) throw new Error(document.errors.map(error => error.message).join('; '));
    const result = document.toJS({ maxAliasCount: 0 });
    if (!isRecord(result)) fail(relative, '$', 'expected a YAML mapping');
    return result;
  } catch (error) {
    if (error instanceof BuilderDiagnostic) throw error;
    fail(relative, '$', error.message);
  }
}

/** Only trim explicit language dictionaries under locale, never params.languages. */
function sourceLocaleOnly(value, language) {
  if (Array.isArray(value)) return value.map(item => sourceLocaleOnly(item, language));
  if (!isRecord(value)) return value;
  const entries = Object.entries(value);
  if (entries.length && entries.every(([key]) => /^[a-z]{2}(?:-[A-Z]{2})?$/.test(key))) {
    return Object.hasOwn(value, language) ? { [language]: sourceLocaleOnly(value[language], language) } : {};
  }
  return Object.fromEntries(entries.map(([key, child]) => [key, sourceLocaleOnly(child, language)]));
}

/**
 * A context is the authoring-contract location, not a schema. Ordinary object
 * fields (including flag.type and params.type) remain plain data.
 */
function childContext(parent, key, owner) {
  const collections = {
    sectionCollection: 'sectionItems',
    flashcardCollection: 'flashcardItems',
    blockCollection: 'blockItems',
    slideCollection: 'slideItems',
    checkpointCollection: 'checkpointItems',
    pairsCollection: 'pairItems',
    slotsCollection: 'slotItems',
  };
  if (collections[parent] && key === 'items') return collections[parent];
  const members = {
    sectionItems: 'section',
    flashcardItems: 'flashcard',
    blockItems: 'block',
    slideItems: 'slide',
    checkpointItems: 'checkpointItem',
    questionGroup: 'question',
    pairItems: 'pair',
    slotItems: 'slot',
  };
  if (members[parent]) return members[parent];
  if (parent === 'questionBank') return 'questionGroup';
  if (parent === 'lesson') {
    if (key === 'section') return 'sectionCollection';
    if (key === 'flashcards') return 'flashcardCollection';
    if (key === 'questions') return 'questionBank';
  }
  if (parent === 'section' && key === 'content') return 'blockCollection';
  if (parent === 'block') {
    if (owner.type === 'carousel' && key === 'slides') return 'slideCollection';
    if (owner.type === 'checkpoint' && key === 'content') return 'checkpointCollection';
  }
  if (parent === 'checkpointItem') {
    if (key === 'question') return 'block';
    if (key === 'answer') return 'blockCollection';
  }
  if (parent === 'question' && key === 'content') return 'questionContent';
  if (parent === 'flashcard' && key === 'content') return 'flashcardContent';
  if (parent === 'flashcardContent' && ['front', 'back', 'hint'].includes(key)) return 'blockCollection';
  if (parent === 'questionContent') {
    if (key === 'answers') return 'questionAnswers';
    if (key === 'pairs') return 'pairsCollection';
    if (key === 'slots') return 'slotsCollection';
    if (['question', 'hint', 'explanation', 'correctSequence', 'distractors', 'sequence'].includes(key))
      return 'blockCollection';
  }
  if (parent === 'questionAnswers' && ['correct', 'incorrect', 'distractors'].includes(key))
    return 'blockCollection';
  if (parent === 'pair' && ['left', 'right'].includes(key)) return 'block';
  if (parent === 'slot' && key === 'correctAnswer') return 'block';
  return 'plain';
}

const factoryContexts = new Set(['lesson', 'section', 'block', 'slide', 'checkpointItem', 'question', 'flashcard']);
const indent = level => '  '.repeat(level);

/**
 * Serialize source fields in original order, wrapping only actual Configurator
 * positions in the Engine factory selected by their type discriminator.
 */
export function renderLessonDraft(lesson, language, factories = loadFactoryRegistry()) {
  const used = new Set();

  function render(value, context, field, level) {
    if (factoryContexts.has(context)) {
      if (!isRecord(value)) fail('content.yaml', field, 'expected an object with type for factory dispatch');
      const type = value.type;
      if (typeof type !== 'string' || !type)
        fail('content.yaml', field + '.type', 'missing type discriminator for ' + context + ' factory dispatch');
      if (context === 'lesson' && type !== 'lesson')
        fail('content.yaml', field + '.type', 'expected lesson type for the Lesson entrypoint');
      const factory = factories[type];
      if (!factory)
        fail('content.yaml', field + '.type', 'unknown type "' + type + '"; no Engine define* factory');
      used.add(factory);
      return factory + '(' + renderObject(value, context, field, level) + ')';
    }
    if (Array.isArray(value)) {
      if (!value.length) return '[]';
      return '[\n' +
        value.map((item, index) => indent(level + 1) + render(item, 'plain', field + '[' + index + ']', level + 1)).join(',\n') +
        '\n' + indent(level) + ']';
    }
    if (isRecord(value)) return renderObject(value, context, field, level);
    if (value === null || ['string', 'number', 'boolean'].includes(typeof value)) return JSON.stringify(value);
    fail('content.yaml', field, 'unsupported YAML value');
  }

  function renderObject(value, context, field, level) {
    const entries = Object.entries(value);
    if (!entries.length) return '{}';
    return '{\n' + entries.map(([key, raw]) => {
      const next = childContext(context, key, value);
      const child = key === 'locale' ? sourceLocaleOnly(raw, language) : raw;
      return indent(level + 1) + JSON.stringify(key) + ': ' +
        render(child, next, field + '.' + key, level + 1);
    }).join(',\n') + '\n' + indent(level) + '}';
  }

  const call = render(lesson, 'lesson', '$', 0);
  const imports = [...used].sort((a, b) => a.localeCompare(b));
  const name = lesson.slug + '_Lesson';
  return 'import { ' + imports.join(', ') + " } from '@svitlo/engine/build';\n\n" +
    'export const ' + name + ' = ' + call + ';\n';
}

/** The UUID path is an output-safety boundary, not editorial validation. */
function targetFor(source, repo) {
  const root = path.resolve(source);
  noSymlinks(root);
  const relative = path.relative(path.resolve(repo), root).split(path.sep).join('/');
  const match = /^content\/((?:languages\/)?[a-z][a-z-]*)\/data\/lessons\/([0-9a-f])\/([0-9a-f-]{36})$/.exec(relative);
  if (!match || !uuidPattern.test(match[3]) || match[3].slice(-1) !== match[2])
    throw new Error('Expected content/<book>/data/lessons/<last-uuid-hex>/<uuid>: ' + relative);
  if (!fs.existsSync(path.join(repo, 'content', match[1], 'package.json')))
    throw new Error('Expected a textbook workspace for ' + relative);
  return { root, lessonId: match[3] };
}

function combineSources(root) {
  const content = parseYaml(path.join(root, 'content.yaml'), 'content.yaml');
  const { documentLanguage, ...lesson } = content;
  if (typeof documentLanguage !== 'string' || !documentLanguage)
    fail('content.yaml', 'documentLanguage', 'required to select authored source-language locale');
  const parts = [
    { filename: 'questions/questions.yaml', property: 'questions' },
    { filename: 'flashcards/flashcards.yaml', property: 'flashcards' },
  ];
  for (const { filename, property } of parts) {
    const location = path.join(root, filename);
    if (!fs.existsSync(location)) continue;
    const parsed = parseYaml(location, filename);
    const { documentLanguage: _sourceLanguage, ...fields } = parsed;
    const value = Object.hasOwn(fields, property) ? fields[property] : fields;
    if (!isRecord(value))
      fail(filename, property, 'expected a mapping of authored ' + property);
    if (Object.hasOwn(lesson, property))
      fail(filename, property, 'already authored in content.yaml; choose one source');
    lesson[property] = value;
  }
  if (typeof lesson.slug !== 'string' || !/^[a-zA-Z][a-zA-Z0-9]*$/.test(lesson.slug))
    fail('content.yaml', 'slug', 'a safe camelCase slug is required for the output filename');
  return { lesson, language: documentLanguage };
}

function writeDraft(file, content, mode) {
  const body = content;
  const rendered = header + checksumLabel + digest(body) + '\n' + body;
  noSymlinks(file);
  if (fs.existsSync(file)) {
    const original = fs.readFileSync(file, 'utf8');
    const expectedHeader = header + checksumLabel;
    if (!original.startsWith(expectedHeader))
      fail(path.basename(file), '$', 'refusing to overwrite a manually authored file');
    const split = original.indexOf('\n', expectedHeader.length);
    const checksum = original.slice(expectedHeader.length, split);
    if (split < 0 || !/^[a-f0-9]{64}$/.test(checksum) || digest(original.slice(split + 1)) !== checksum)
      fail(path.basename(file), '$', 'generated file was modified manually');
    if (original === rendered) return 0;
    if (mode === 'check') fail(path.basename(file), '$', 'stale draft; run content:generate:lessons');
    fs.writeFileSync(file, rendered);
    return 1;
  }
  if (mode === 'check') fail(path.basename(file), '$', 'missing draft; run content:generate:lessons');
  fs.writeFileSync(file, rendered, { flag: 'wx' });
  return 1;
}

export function runOne(source, mode = 'check', repo = repoRoot) {
  if (!['generate', 'check'].includes(mode)) throw new Error('Mode must be generate or check');
  const target = targetFor(source, repo);
  const { lesson, language } = combineSources(target.root);
  const draft = renderLessonDraft(lesson, language);
  const entryName = lesson.slug + '.data.ts';
  for (const name of fs.readdirSync(target.root)) {
    if (name.endsWith('.data.ts') && name !== entryName)
      fail(name, '$', 'competing Lesson data entrypoint; refusing to create another');
  }
  const changed = writeDraft(path.join(target.root, entryName), draft, mode);
  return { changed, files: [entryName], lessonId: target.lessonId };
}

function discover(repo) {
  const content = path.join(repo, 'content');
  if (!fs.existsSync(content)) return [];
  const roots = [];
  for (const entry of fs.readdirSync(content, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const folder = path.join(content, entry.name);
    const workspaces = entry.name === 'languages'
      ? fs.readdirSync(folder, { withFileTypes: true }).filter(item => item.isDirectory()).map(item => path.join(folder, item.name))
      : [folder];
    for (const workspace of workspaces) {
      const lessons = path.join(workspace, 'data/lessons');
      if (!fs.existsSync(lessons)) continue;
      for (const bucket of fs.readdirSync(lessons, { withFileTypes: true })) {
        if (!bucket.isDirectory() || !/^[0-9a-f]$/.test(bucket.name)) continue;
        for (const entry of fs.readdirSync(path.join(lessons, bucket.name), { withFileTypes: true })) {
          if (!entry.isDirectory()) continue;
          const location = path.join(lessons, bucket.name, entry.name);
          if (fs.existsSync(path.join(location, 'content.yaml'))) roots.push(location);
        }
      }
    }
  }
  return roots.sort();
}

export function main(args = process.argv.slice(2), repo = repoRoot) {
  const [mode, ...rest] = args;
  if (!['generate', 'check'].includes(mode) || (rest.length && !(rest.length === 2 && rest[0] === '--source')))
    throw new Error('Usage: node shared/engine/scripts/lessonBuilder/lessonBuilder.mjs generate|check [--source content/<book>/data/lessons/<bucket>/<uuid>]');
  const roots = rest.length ? [path.resolve(repo, rest[1])] : discover(repo);
  for (const root of roots) {
    const result = runOne(root, mode, repo);
    console.log(result.lessonId + ': ' + (mode === 'check' ? 'up to date' : result.changed + ' file(s) written'));
  }
  console.log('Processed ' + roots.length + ' Lesson draft source(s)');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
