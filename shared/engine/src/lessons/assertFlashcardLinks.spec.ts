import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { assertFlashcardLinks } from './assertFlashcardLinks';
import { linkFlashcards, type FlashcardLink } from './linkFlashcards';

const card = (id: string) => ({ id, front: [], back: [], hint: [], tags: [], flags: [] });
const cards = [card('a'), card('b'), card('c')];
const edge = (id: string, type: FlashcardLink['type'], from = 'a', to = 'b'): FlashcardLink => ({
  relationshipId: id,
  type,
  sourceFlashcardId: from,
  targetFlashcardId: to,
});

describe('assertFlashcardLinks', () => {
  it('accepts legacy cards and all canonical, mirrored links generated by the Engine', () => {
    assert.doesNotThrow(() => assertFlashcardLinks(cards));
    const linked = linkFlashcards(cards, [
      edge('reciprocal', 'reverse'),
      edge('precursor', 'prerequisite', 'a', 'b'),
      edge('part', 'partOf', 'b', 'c'),
    ]);
    assert.doesNotThrow(() => assertFlashcardLinks(linked));
  });

  it('rejects one-sided or improperly oriented links', () => {
    const valid = linkFlashcards(cards, [edge('ab', 'prerequisite')]);
    assert.throws(() => assertFlashcardLinks([valid[0], { ...valid[1], relationships: [] }, valid[2]]), /mirrored/);
    const badPosition = valid.map((item, index) =>
      index === 1 ? { ...item, relationships: [{ ...item.relationships![0], position: 'source' }] } : item,
    );
    assert.throws(() => assertFlashcardLinks(badPosition), /Inconsistent mirrored/);
  });

  it('rejects invalid types, self links, unknown targets and duplicate edge keys', () => {
    const valid = linkFlashcards(cards, [edge('ab', 'reverse')]);
    const corrupt = (key: string, value: unknown) =>
      valid.map((item, index) =>
        index === 0 ? { ...item, relationships: [{ ...item.relationships![0], [key]: value }] } : item,
      );
    assert.throws(() => assertFlashcardLinks(corrupt('type', 'nonexistent')), /Invalid Flashcard relationship/);
    assert.throws(() => assertFlashcardLinks(corrupt('relatedFlashcardId', 'a')), /Invalid Flashcard relationship/);
    assert.throws(
      () => assertFlashcardLinks(corrupt('relatedFlashcardId', 'missing')),
      /Invalid Flashcard relationship/,
    );
    const duplicate = valid.map((item, index) =>
      index === 0 ? { ...item, relationships: [item.relationships![0], item.relationships![0]] } : item,
    );
    assert.throws(() => assertFlashcardLinks(duplicate), /Invalid Flashcard relationship/);
  });

  it('rejects duplicate semantic pairs even with distinct relationship IDs', () => {
    const result = linkFlashcards(cards, [edge('r1', 'contrast', 'a', 'b')]);
    const copyA = {
      ...result[0],
      relationships: [
        ...result[0].relationships!,
        {
          relationshipId: 'r2',
          type: 'contrast' as const,
          relatedFlashcardId: 'b',
          position: 'peer' as const,
        },
      ],
    };
    const copyB = {
      ...result[1],
      relationships: [
        ...result[1].relationships!,
        {
          relationshipId: 'r2',
          type: 'contrast' as const,
          relatedFlashcardId: 'a',
          position: 'peer' as const,
        },
      ],
    };
    assert.throws(() => assertFlashcardLinks([copyA, copyB, result[2]]), /Duplicate Flashcard semantic relation/);
  });

  it('rejects cycles for prerequisite, partOf, and precedes while allowing causal feedback loops', () => {
    for (const type of ['prerequisite', 'partOf', 'precedes'] as const) {
      const linked = linkFlashcards(cards, [
        edge('ab', type, 'a', 'b'),
        edge('bc', type, 'b', 'c'),
        edge('ca', type, 'c', 'a'),
      ]);
      assert.throws(() => assertFlashcardLinks(linked), /Cyclic Flashcard/);
    }
    const feedback = linkFlashcards(cards, [
      edge('ab', 'causes', 'a', 'b'),
      edge('bc', 'causes', 'b', 'c'),
      edge('ca', 'causes', 'c', 'a'),
    ]);
    assert.doesNotThrow(() => assertFlashcardLinks(feedback));
  });
});
